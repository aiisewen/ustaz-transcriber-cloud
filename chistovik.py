# -*- coding: utf-8 -*-
"""
Чистовик — эталонный литературный перевод длинных подкастов.

Формат по образцу вычитанного перевода («свадебное угощение.docx»):
короткие абзацы, Пророк (сав), цитаты с источником, арабизмы,
пояснения через тире, без таймкодов и служебных пометок.

Длинный транскрипт переводится кусками: каждый следующий кусок видит
хвост уже готового перевода, чтобы текст оставался связным.
"""

import re
from pathlib import Path

import anthropic

# ~4000 знаков на кусок — влезает в один ответ модели с запасом
CHUNK_CHARS = 4000
# сколько хвоста готового перевода показывать следующему куску
TAIL_CHARS = 600

CHISTOVIK_SYSTEM = """Ты редактор-переводчик религиозных выступлений с кыргызского на русский.
Готовишь ЧИСТОВИК — финальный литературный текст проповеди для публикации,
по образцу профессионально вычитанных переводов.

ГЛАВНЫЙ ПРИНЦИП: перевод по смыслу, а не по словам. Текст должен читаться так,
будто устаз изначально говорил по-русски. Спокойный назидательный тон,
без драматизации.

Правила чистовика:
1. СТРОГО следуй глоссарию терминов ниже.
2. Разбивай текст на КОРОТКИЕ АБЗАЦЫ по одной мысли (1–4 предложения),
   между абзацами пустая строка. Риторический вопрос может стоять отдельным
   абзацем («Почему?»).
3. Пророка упоминай единообразно: «Пророк (сав)». Не «ﷺ», не «Мухаммад».
4. Цитаты оформляй в кавычках-«ёлочках» и всегда называй источник:
   «Всевышний Аллах в суре „Аль-Ахзаб" говорит: „…"», «Пророк (сав) сказал: „…"».
5. Арабизмы транслитерируй и оставляй: Альхамдулиллях, иншаАллах, рия, сунна,
   дастархан. Редкий термин поясняй через тире прямо в предложении:
   «людям из Ахль ас-Суффа — бедным сподвижникам, которые находились возле мечети».
6. Никаких таймкодов, пометок [неразборчиво], ремарок зала и служебных вставок —
   это чистовик для читателя. Тёмное место восстанавливай по контексту;
   если восстановить нельзя — аккуратно опусти, не выдумывая содержания.
7. Убирай мусор устной речи (оговорки, самоповторы, фальстарты), но сохраняй
   голос проповедника: обращения «Посмотрите…», «Представьте…», риторические
   вопросы, личные истории («У меня есть один хороший брат…»).
8. Народные мудрости и пословицы — по смыслу, в кавычках:
   «Гость ест не столько пищу, сколько отношение хозяина».
9. НЕ УСИЛИВАЙ ЭМОЦИЮ: восклицания только там, где восклицает устаз; слова той же
   силы, без иронии и оценочных частиц. Смысл не сокращать и не добавлять.
10. Верни ТОЛЬКО текст чистовика, без вступлений и комментариев.

Образец стиля (фрагмент эталонного перевода):
---
Всевышний Аллах в суре «Аль-Ахзаб» говорит: «А если вас пригласили, то входите, а после того как поедите, расходитесь». Также Пророк (сав) сказал: «Если кого-либо из вас пригласили на угощение, пусть он придёт».

Из этого мы понимаем, что мусульманину следует принимать приглашение. Особенно это касается приглашения на свадьбу.

Однажды Пророк (сав) принёс еду людям из Ахль ас-Суффа — бедным сподвижникам, которые находились возле мечети и часто испытывали голод. Он не просто накормил их, но и сам сел рядом с ними и поел вместе с ними.

И сказал: «Альхамдулиллях, я сижу вместе с любимыми рабами Аллаха».

У меня есть один хороший брат. Он построил дом и решил устроить праздник по этому случаю. Но знаете, кого он пригласил? Он пригласил детей из детского дома.

Человека украшает не его должность, не богатство и не власть. В народе есть такая мудрость: «Гость ест не столько пищу, сколько отношение хозяина».
---

Глоссарий:
{glossary}"""


def split_chunks(text: str) -> list[str]:
    """Разбить транскрипт на куски ≤ CHUNK_CHARS, по границам таймкодов [м:сс]."""
    blocks = re.split(r"(?=\[\d+:\d{2}\])", text)
    blocks = [b for b in blocks if b.strip()]
    chunks, cur = [], ""
    for b in blocks:
        if cur and len(cur) + len(b) > CHUNK_CHARS:
            chunks.append(cur)
            cur = b
        else:
            cur += b
    if cur.strip():
        chunks.append(cur)
    # запасной путь: текст без таймкодов и длиннее лимита — режем по абзацам/предложениям
    if len(chunks) == 1 and len(chunks[0]) > CHUNK_CHARS * 1.5:
        parts = re.split(r"(?<=[.!?])\s+", chunks[0])
        chunks, cur = [], ""
        for p in parts:
            if cur and len(cur) + len(p) > CHUNK_CHARS:
                chunks.append(cur)
                cur = p
            else:
                cur += (" " if cur else "") + p
        if cur.strip():
            chunks.append(cur)
    return chunks


def make_chistovik(client: anthropic.Anthropic, kyrgyz_text: str, glossary: str,
                   progress_cb=None, economy: bool = True) -> str:
    """Перевести длинный транскрипт в эталонный чистовик (кусками, связно).

    economy=True — Sonnet (в ~5 раз дешевле, чуть проще стиль);
    economy=False — Opus (максимальное качество).
    """
    chunks = split_chunks(kyrgyz_text)
    system = CHISTOVIK_SYSTEM.format(glossary=glossary)
    done: list[str] = []
    for i, chunk in enumerate(chunks):
        if progress_cb:
            progress_cb(i, len(chunks))
        if done:
            tail = "".join(done)[-TAIL_CHARS:]
            user = (f"Конец уже готового чистовика (для связности, заново НЕ переводи):\n"
                    f"…{tail}\n\n"
                    f"Продолжи чистовик — переведи следующий фрагмент транскрипта:\n\n{chunk}")
        else:
            user = f"Переведи в чистовик этот фрагмент транскрипта (начало выступления):\n\n{chunk}"
        resp = None
        # экономный режим — Sonnet; максимум — Opus с запасной попыткой на Sonnet
        if economy:
            attempts = ["claude-sonnet-5"] * 4
        else:
            attempts = ["claude-opus-5", "claude-opus-5", "claude-opus-5", "claude-sonnet-5"]
        for attempt, model in enumerate(attempts):
            try:
                resp = client.messages.create(
                    model=model,
                    max_tokens=8000,
                    system=system,
                    messages=[{"role": "user", "content": user}],
                )
                break
            except anthropic.APIConnectionError:
                if attempt == len(attempts) - 1:
                    raise
                import time as _time
                _time.sleep(15 * (attempt + 1))
            except anthropic.APIStatusError as e:
                # 429/5xx/529 — временные, повторяем; остальное наверх
                if attempt == len(attempts) - 1 or e.status_code not in (429, 500, 502, 503, 504, 529):
                    raise
                import time as _time
                _time.sleep(15 * (attempt + 1))
        if resp.stop_reason == "refusal":
            done.append("\n\n[Фрагмент отклонён моделью — переведи вручную]\n\n")
            continue
        piece = "".join(b.text for b in resp.content if b.type == "text").strip()
        done.append(("\n\n" if done else "") + piece)
    return "".join(done).strip()


def export_docx(text: str, title: str, out_path: Path) -> Path:
    """Сохранить чистовик в Word: абзац на блок, пустая строка между — как в эталоне."""
    import docx
    doc = docx.Document()
    if title:
        h = doc.add_paragraph()
        h.add_run(title).bold = True
        doc.add_paragraph()
    for para in re.split(r"\n\s*\n", text):
        para = para.strip()
        if not para:
            continue
        doc.add_paragraph(para.replace("\n", " "))
        doc.add_paragraph()
    doc.save(str(out_path))
    return out_path
